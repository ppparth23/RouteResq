"""VULNEX AI — Secure IoT Firmware Analysis and Synthesis API Endpoints.

Provides endpoints for:
- Embedded C/C++ firmware static vulnerability analysis
- AI-driven secure firmware component synthesis
- Insecure firmware code refactoring to memory-safe patterns
- Pre-curated high-assurance firmware templates
- Cross-compiler and static toolchain availability status
"""

import logging
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, HTTPException, Query, status

from app.schemas.v1 import (
    FirmwareAnalysisRequest,
    FirmwareAnalysisResponse,
    FirmwareRefactorRequest,
    FirmwareRefactorResponse,
    FirmwareSynthesisRequest,
    FirmwareSynthesisResponse,
    FirmwareTemplate,
)
from app.services.firmware_service import FirmwareService
from app.services.scanners.toolchain import ToolchainDetector
from app.storage.database import list_firmware_syntheses

logger = logging.getLogger("vulnex.api.firmware")

router = APIRouter(prefix="/firmware", tags=["Firmware Security & Synthesis"])


@router.post("/analyze", response_model=FirmwareAnalysisResponse, status_code=status.HTTP_200_OK)
def analyze_firmware(request: FirmwareAnalysisRequest) -> FirmwareAnalysisResponse:
    """
    Analyzes embedded C/C++ source code for IoT firmware security vulnerabilities:
    - Firmware Memory Security (buffer overflows, UAF, double free, null dereference)
    - Device Communication (plaintext MQTT, insecure HTTP, TLS verification bypass)
    - Firmware Update Security (unsigned OTA, missing rollback protection)
    - Device Authentication (hardcoded credentials, exposed Wi-Fi PSKs)
    - Embedded System Security (unbounded task stack depth, verbose UART debugging)
    """
    try:
        return FirmwareService.analyze_firmware(request)
    except Exception as e:
        logger.error(f"Error analyzing firmware: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Firmware analysis failed: {str(e)}"
        )


@router.post("/synthesize", response_model=FirmwareSynthesisResponse, status_code=status.HTTP_200_OK)
def synthesize_firmware(request: FirmwareSynthesisRequest) -> FirmwareSynthesisResponse:
    """
    AI-Powered Secure Firmware Component Synthesizer.
    Generates memory-safe, hardened C/C++ source code, header files, configuration,
    unit tests, and security explanations for ESP32, STM32, FreeRTOS, Zephyr, and Arduino.
    """
    try:
        return FirmwareService.synthesize_secure_firmware(request)
    except Exception as e:
        logger.error(f"Error synthesizing secure firmware: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Secure firmware synthesis failed: {str(e)}"
        )


@router.post("/refactor", response_model=FirmwareRefactorResponse, status_code=status.HTTP_200_OK)
def refactor_firmware(request: FirmwareRefactorRequest) -> FirmwareRefactorResponse:
    """
    Refactors insecure embedded C/C++ code snippets into memory-safe, hardened equivalents.
    Generates unified diffs and explains security benefits.
    """
    try:
        return FirmwareService.refactor_insecure_code(request)
    except Exception as e:
        logger.error(f"Error refactoring firmware code: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Firmware refactoring failed: {str(e)}"
        )


@router.get("/templates", response_model=List[FirmwareTemplate], status_code=status.HTTP_200_OK)
def get_firmware_templates() -> List[FirmwareTemplate]:
    """
    Returns curated, high-assurance secure component templates for ESP32, STM32, and FreeRTOS.
    """
    return FirmwareService.get_templates()


@router.get("/toolchain", response_model=Dict[str, Any], status_code=status.HTTP_200_OK)
def get_toolchain_status() -> Dict[str, Any]:
    """
    Returns the real-time availability and version status of C/C++ host and cross-compilation toolchains:
    - Semgrep AST scanner
    - Clang & Clang-Tidy
    - Cppcheck
    - Host GCC / G++
    - ARM Embedded Toolchain (arm-none-eabi-gcc)
    - Custom C/C++ AST analyzer
    """
    return ToolchainDetector.get_tool_status()


@router.get("/history", response_model=List[Dict[str, Any]], status_code=status.HTTP_200_OK)
def get_synthesis_history(limit: int = Query(20, ge=1, le=100)) -> List[Dict[str, Any]]:
    """
    Retrieves previous secure firmware syntheses generated by VULNEX AI.
    """
    return list_firmware_syntheses(limit=limit)
